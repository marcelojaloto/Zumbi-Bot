/** Reserva máxima por tipo de munição (maior entre as armas que a usam). */
export function ammoCap(t: AmmoType): number {
  let cap = 0;
  for (const w of Object.values(FIREARMS)) {
    if (w.ammo === t && typeof w.reserveMax === 'number') cap = Math.max(cap, w.reserveMax);
  }
  return cap;
}
