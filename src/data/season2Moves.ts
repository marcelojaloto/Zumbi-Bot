const heavy = (
  damage: number,
  dtype: HitSpec['dtype'],
  kb: number,
  launch: number,
  extra: Partial<HitSpec> = {},
) =>
  ({
    damage,
    dtype,
    knockback: kb,
    launch,
    knockdown: true,
    hitstun: 28,
    hitstop: 6,
    heavy: true,
    ...extra,
  }) satisfies HitSpec;

const blast = (
  radius: number,
  damage: number,
  dtype: ExplosionSpec['dtype'],
  extra: Partial<ExplosionSpec> = {},
) =>
  ({
    radius,
    damage,
    minMult: 0.45,
    dtype,
    knockback: 6,
    launch: 3,
    selfMult: 0,
    ...extra,
  }) satisfies ExplosionSpec;

