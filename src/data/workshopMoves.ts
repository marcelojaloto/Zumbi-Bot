const heavy = (
  damage: number,
  dtype: HitSpec['dtype'],
  kb: number,
  launch: number,
  extra: Partial<HitSpec> = {},
) =>
  ({
    damage,
    dtype,
    knockback: kb,
    launch,
    knockdown: true,
    hitstun: 28,
    hitstop: 6,
    heavy: true,
    ...extra,
  }) satisfies HitSpec;

const blast = (
  radius: number,
  damage: number,
  dtype: ExplosionSpec['dtype'],
  extra: Partial<ExplosionSpec> = {},
) =>
  ({
    radius,
    damage,
    minMult: 0.45,
    dtype,
    knockback: 6,
    launch: 3,
    selfMult: 0,
    ...extra,
  }) satisfies ExplosionSpec;

/** Especial: custo, invencibilidade nos quadros ativos e o resto do golpe. */
const special = (m: Omit<MeleeMoveDef, 'special'>): MeleeMoveDef => ({
  manaCost: 30,
  hpCost: 10,
  ...m,
  special: true,
});

